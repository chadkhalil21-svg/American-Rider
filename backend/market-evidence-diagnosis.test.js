'use strict';
const assert=require('node:assert/strict');
const {evidenceProblem}=require('./market-evidence-diagnosis');
const M=require('./market-readiness');
const {markets}=require('./markets');
const {regionById}=require('./regions');
const market=markets().find(m=>m.id==='fl-miami-dade');
const region=regionById(market.regionId);
const version=M.manifestFor(market,region).version;
const now=1800000000000;
const id='company_insurance_bound';
const good={reference:'independently-reviewed-real-record',issuer:'Real issuer',verifiedBy:'named-person',
  reviewedAt:now-3000,validUntil:now+5000,manifestVersion:version};
for(let pass=0;pass<2;pass++){
 const absent=evidenceProblem(id,undefined,version,now);
 assert.equal(absent.code,'record_absent');
 assert.match(absent.reason,/does not establish/);
 assert.equal(evidenceProblem(id,good,version,now),null);
 assert.equal(evidenceProblem(id,{...good,manifestVersion:'old'},version,now).code,'record_version_mismatch');
 assert.equal(evidenceProblem(id,{...good,reviewedAt:now+1},version,now).code,'record_invalid');
 assert.equal(evidenceProblem(id,{...good,reviewedAt:NaN},version,now).code,'record_invalid');
 assert.equal(evidenceProblem(id,{...good,validUntil:now-1},version,now).code,'record_expired');
 assert.equal(evidenceProblem(id,{...good,validUntil:good.reviewedAt},version,now).code,'record_invalid');
 assert.equal(evidenceProblem(id,{...good,reference:''},version,now).code,'record_invalid');
 assert.equal(evidenceProblem(id,{...good,issuer:''},version,now).code,'record_invalid');
 assert.equal(evidenceProblem(id,{...good,verifiedBy:''},version,now).code,'record_invalid');
 assert.equal(evidenceProblem(id,[],version,now).code,'record_absent');
 const empty=M.readinessFor({market,region,now});
 assert.equal(empty.readyToActivate,false);
 assert.equal(empty.missing.length,M.REQUIRED_EVIDENCE.length);
 assert.ok(empty.missing.every(x=>x.code==='record_absent'));
 const verified=Object.fromEntries(M.REQUIRED_EVIDENCE.map(k=>[k,{...good}]));
 const record={status:'active',manifestVersion:version,evidence:verified};
 assert.equal(M.readinessFor({market,region,record,now}).status,'active');
 const tampered={...record,evidence:{...verified,[id]:{...good,reviewedAt:now+6000}}};
 assert.equal(M.readinessFor({market,region,record:tampered,now}).status,'waitlist');
 const uncommissioned=M.readinessFor({market,region,record,now,providerMissing:['screening_provider']});
 assert.equal(uncommissioned.status,'waitlist');
 assert.equal(uncommissioned.missing[0].code,'production_verification_missing');
}
console.log('PASS twice: absent is not failed work, stale/expired/future proof refused, real gates unchanged');
