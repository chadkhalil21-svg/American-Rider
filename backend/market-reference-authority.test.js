const assert=require('node:assert/strict');
const {qualification,referenceScopeForPickup}=require('./market-reference-authority');
const plan={minimumIndependentFamilies:2,maxObservationAgeDays:90};
const now=Date.parse('2026-10-01T12:00:00Z');
const cell={referenceTotalCents:2000,targetTotalCents:1800,travelerTotalComparable:true,observations:40,evidenceFamilies:['government-trips','independent-audit'],sources:['government-a','audit-b'],providers:['provider-a','provider-b'],maxProviderShare:0.5,latestObservedAt:'2026-10-01T11:00:00Z',oldestObservedAt:'2026-10-01T10:30:00Z'};
const promoted={asOf:'2026-10-01T11:30:00Z',promotion:{status:'promoted',snapshotAsOf:'2026-10-01T11:30:00Z',holdoutPassed:true,economicsPassed:true,routerPassed:true},cells:{x:cell}};
assert.equal(qualification(null,plan).ok,false);
assert.equal(qualification({asOf:'2026-10-01T11:30:00Z',promotion:{status:'candidate'},cells:{}},plan).ok,false);
assert.equal(qualification({...promoted,promotion:{...promoted.promotion,holdoutPassed:false}},plan).ok,false);
assert.equal(qualification(promoted,plan).ok,true);
assert.equal(qualification(promoted,plan,cell,now).ok,true);
assert.equal(qualification(promoted,plan,{...cell,oldestObservedAt:undefined},now).ok,false,'old snapshots cannot attest freshness');
assert.equal(qualification(promoted,plan,{...cell,oldestObservedAt:'2026-08-15T10:00:00Z'},now).ok,false,'one recent observation cannot revive stale batch');
assert.equal(qualification(promoted,plan,{...cell,oldestObservedAt:'2026-10-01T11:30:00Z'},now).ok,false,'earliest observation cannot exceed newest');
assert.equal(qualification(promoted,plan,{...cell,travelerTotalComparable:false},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,observations:2},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,referenceTotalCents:2200},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,maxProviderShare:undefined},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,evidenceFamilies:['government-trips']},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,sources:['only-one']},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,maxProviderShare:0.71},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,latestObservedAt:'2026-01-01T00:00:00Z'},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,latestObservedAt:'2026-10-01T12:06:00Z'},now).ok,false);
assert.equal(qualification(promoted,plan,{...cell,latestObservedAt:'2026-10-01T12:05:00Z'},now).ok,true);
assert.equal(referenceScopeForPickup({lat:25.7959,lng:-80.287}),'fl-miami-dade');
assert.equal(referenceScopeForPickup({lat:26.0742,lng:-80.1506}),'fl-broward');
assert.equal(referenceScopeForPickup({lat:26.6832,lng:-80.0956}),'fl-palm-beach');
assert.equal(referenceScopeForPickup({lat:41.8781,lng:-87.6298}),null);
console.log('market-reference runtime authority tests passed');
