const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pickupDate,pickupMinutes,nextDate,resolvePickupWall}=require('./scheduleclock');
const zone='America/New_York';
assert.equal(pickupDate(Date.parse('2026-10-04T02:30:00Z'),zone),'2026-10-03');
assert.equal(pickupMinutes(Date.parse('2026-10-04T02:30:00Z'),zone),22*60+30);
assert.equal(nextDate('2026-12-31'),'2027-01-01');
assert.equal(resolvePickupWall('2026-03-08','1:30','AM',zone).atMs,Date.parse('2026-03-08T06:30:00Z'));
assert.equal(resolvePickupWall('2026-03-08','2:30','AM',zone).code,'nonexistent_wall_time');
assert.equal(resolvePickupWall('2026-03-08','3:30','AM',zone).atMs,Date.parse('2026-03-08T07:30:00Z'));
assert.equal(resolvePickupWall('2026-11-01','1:30','AM',zone).code,'ambiguous_wall_time');
assert.equal(resolvePickupWall('2026-11-01','2:30','AM',zone).atMs,Date.parse('2026-11-01T07:30:00Z'));
assert.equal(resolvePickupWall('2026-10-06','6:30','AM','America/Los_Angeles').atMs,Date.parse('2026-10-06T13:30:00Z'));
assert.equal(resolvePickupWall('2026-02-30','6:30','AM',zone).ok,false);
assert.equal(resolvePickupWall('2026-10-06','6:30','AM','Invalid/Zone').ok,false);
const server=fs.readFileSync(path.join(__dirname,'server.js'),'utf8');
const route=server.split("app.post('/travel/schedule',")[1].split('// --- Who can bring a lost item back.')[0];
assert.ok(route.indexOf('resolvePickupWall(')>-1&&route.indexOf('resolvePickupWall(')<route.indexOf('authoritativeFare('));
assert.match(route,/resolved\.atMs !== atMs/);
assert.match(route,/b\.pickupTimeZone !== timeZone/);
assert.match(route,/pickupDate: b\.pickupDate, pickupTimeZone: timeZone/);
console.log('PASS pickup-local calendar, DST gap/overlap refusal and pre-fare server validation');
